create table if not exists test_cases (
    id              integer generated by default as identity primary key,
    test_case_id    varchar(100) not null unique,
    test_case_name  varchar(255) not null,
    page            varchar(255) not null default '',
    steps           text not null default '',
    expected_result text,
    enabled         boolean not null default true,
    source_file     varchar(255),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);

alter table test_cases add column if not exists page varchar(255) not null default '';
alter table test_cases add column if not exists steps text not null default '';
alter table test_cases add column if not exists source_file varchar(255);

create table if not exists executions (
    id            integer generated by default as identity primary key,
    status        varchar(20) not null,
    app_url       varchar(500) not null default '',
    app_name      varchar(255),
    started_at    timestamptz,
    completed_at  timestamptz,
    created_at    timestamptz not null default now()
);

alter table executions add column if not exists app_url varchar(500) not null default '';
alter table executions add column if not exists app_name varchar(255);

create table if not exists test_results (
    id              integer generated by default as identity primary key,
    execution_id    integer not null references executions(id) on delete cascade,
    test_case_id    integer not null references test_cases(id) on delete cascade,
    status          varchar(20) not null,
    actual_result   text,
    error_message   text,
    started_at      timestamptz,
    completed_at    timestamptz,
    duration_ms     integer,
    failed_step     integer,
    video_path      text,
    video_data      bytea,
    has_video       boolean not null default false
);

alter table test_results add column if not exists failed_step integer;
alter table test_results add column if not exists video_path text;
alter table test_results add column if not exists video_data bytea;
alter table test_results add column if not exists has_video boolean not null default false;

create index if not exists ix_test_results_execution on test_results(execution_id);
create index if not exists ix_executions_status on executions(status);
create index if not exists ix_test_results_status on test_results(status);
create index if not exists ix_test_results_exec_status on test_results(execution_id, status);
create index if not exists ix_test_cases_enabled on test_cases(enabled);
create index if not exists ix_test_cases_source_file on test_cases(source_file);
create index if not exists ix_executions_created_at on executions(created_at desc);
create index if not exists ix_executions_id_desc on executions(id desc);
create index if not exists ix_test_results_failed_recent on test_results(id desc) where status = 'failed';